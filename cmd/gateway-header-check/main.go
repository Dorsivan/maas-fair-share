// Command gateway-header-check is the UNI-33 conformance check: it fails
// loudly (non-zero exit, one line per offender) if any HTTPRoute reachable
// through an InferencePool is not covered by an AuthPolicy that overwrites
// x-llm-d-inference-objective.
//
// This directory is its own Go module (see go.mod), separate from the
// repository root, carrying a committed vendor/ so it builds with no
// network access -- see docs/gateway-header-stripping.md, "Building this
// check air-gapped". That also means "go run ./cmd/gateway-header-check"
// does not work from the repository root; build it once from here instead:
//
//	(cd cmd/gateway-header-check && go build -o ../../bin/gateway-header-check .)
//
// Then run the binary against the live cluster -- the authoritative target,
// since the real HTTPRoutes and AuthPolicy on maas-fairness-poc are
// generated by odh-model-controller/KServe and are not checked into this
// repository:
//
//	oc --token="$OPENSHIFT_TOKEN" --server=https://api.ocp.paladinaura.com:6443 \
//	  get httproute,gateway,authpolicy -A -o yaml \
//	  | bin/gateway-header-check -
//
// Or against a file (a saved snapshot, or any deploy/*.yaml), from the
// repository root:
//
//	bin/gateway-header-check deploy/poc/03-gateway.yaml
//
// For quick local iteration with network access, "go run ." from this
// directory works too. See docs/gateway-header-stripping.md for why this
// must run against a live snapshot to mean anything on this cluster.
package main

import (
	"fmt"
	"io"
	"os"

	"github.com/Dorsivan/maas-fair-share/conformance/gatewayheaders"
)

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintf(os.Stderr, "usage: %s <manifest-file.yaml | ->\n", os.Args[0])
		os.Exit(2)
	}

	data, err := readInput(os.Args[1])
	if err != nil {
		fmt.Fprintf(os.Stderr, "gateway-header-check: %v\n", err)
		os.Exit(2)
	}

	docs, err := gatewayheaders.ParseYAML(data)
	if err != nil {
		fmt.Fprintf(os.Stderr, "gateway-header-check: %v\n", err)
		os.Exit(2)
	}

	violations, err := gatewayheaders.Check(docs)
	if err != nil {
		fmt.Fprintf(os.Stderr, "gateway-header-check: %v\n", err)
		os.Exit(2)
	}

	if len(violations) == 0 {
		fmt.Println("gateway-header-check: OK -- every InferencePool-backed HTTPRoute overwrites " +
			gatewayheaders.ObjectiveHeaderKey)
		return
	}

	fmt.Fprintf(os.Stderr, "gateway-header-check: FAIL -- %d route(s) do not overwrite %s:\n",
		len(violations), gatewayheaders.ObjectiveHeaderKey)
	for _, v := range violations {
		fmt.Fprintf(os.Stderr, "  - %s\n", v)
	}
	os.Exit(1)
}

func readInput(path string) ([]byte, error) {
	if path == "-" {
		return io.ReadAll(os.Stdin)
	}
	return os.ReadFile(path)
}
