// Package gatewayheaders checks that every Gateway API HTTPRoute fronting the
// inference path is covered by a Kuadrant AuthPolicy that overwrites the
// x-llm-d-inference-objective header on every request.
//
// Why this header and not the others: the EPP's own header-alias resolution
// (github.com/llm-d/llm-d-router v0.11.0, pkg/epp/metadata/consts.go) prefers
// x-llm-d-inference-objective over the gateway-authored
// x-gateway-inference-objective whenever both are present. A client that sets
// the first wins outright -- the EPP has no way to tell client-supplied from
// gateway-supplied once both headers reach it, because it only ever reads one
// map. The plugin in this repo overwrites the fairness-id headers itself
// (see docs/design.md, "Security: headers must be stripped at the gateway"),
// but there is no equivalent plugin seam for the objective header: priority
// band selection happens in the EPP's Director before any of our plugins run.
// So the only defense is upstream of the EPP, in the request path the gateway
// controls.
//
// On this cluster the real HTTPRoutes and the AuthPolicy that protects them
// are generated by the odh-model-controller / KServe reconciler, not checked
// into this repository -- see docs/gateway-header-stripping.md. That is why
// this checker is built to run against EITHER a static set of manifests
// (sigs.k8s.io/yaml multi-doc files under deploy/, for fixture-driven unit
// tests) OR a live snapshot (`oc get httproute,gateway,authpolicy -A -o yaml`,
// which the API server returns as a single `kind: List`). Only the live-mode
// run is authoritative for this cluster; the static mode exists so the
// matching logic itself has a fast, offline test.
package gatewayheaders

import (
	"bytes"
	"fmt"
	"sort"
	"strings"

	"sigs.k8s.io/yaml"
)

// ObjectiveHeaderKey is the header the EPP trusts over any gateway-authored
// alias. See github.com/llm-d/llm-d-router v0.11.0 pkg/epp/metadata/consts.go:
// ObjectiveKey = "x-llm-d-inference-objective", checked before the deprecated
// OldObjectiveKey = "x-gateway-inference-objective".
const ObjectiveHeaderKey = "x-llm-d-inference-objective"

// object is a generic decoded Kubernetes manifest. Using map[string]any
// rather than typed Gateway API / Kuadrant structs keeps this package free of
// new module dependencies -- it only ever needs a handful of fields, and the
// clusters this runs against may have either the x-k8s.io or k8s.io
// InferencePool CRD, or both.
type object map[string]any

// Violation names one HTTPRoute that reaches an InferencePool without a
// matching header-stripping AuthPolicy in scope.
type Violation struct {
	Namespace string
	Name      string
	Reason    string
}

func (v Violation) String() string {
	return fmt.Sprintf("%s/%s: %s", v.Namespace, v.Name, v.Reason)
}

// ParseYAML splits a multi-document YAML stream (documents separated by a
// line containing only "---", the format both `deploy/*.yaml` and
// `oc get -o yaml` for a single resource use) into decoded objects. A
// `kind: List` document (what `oc get <several kinds> -A -o yaml` produces)
// is expanded into its `items`.
func ParseYAML(data []byte) ([]object, error) {
	var docs []object
	for _, raw := range splitYAMLDocuments(data) {
		raw = bytes.TrimSpace(raw)
		if len(raw) == 0 {
			continue
		}
		var doc object
		if err := yaml.Unmarshal(raw, &doc); err != nil {
			return nil, fmt.Errorf("decoding YAML document: %w", err)
		}
		if doc == nil {
			continue
		}
		if kind, _ := doc["kind"].(string); kind == "List" {
			items, _ := doc["items"].([]any)
			for _, item := range items {
				if m, ok := item.(map[string]any); ok {
					docs = append(docs, object(m))
				}
			}
			continue
		}
		docs = append(docs, doc)
	}
	return docs, nil
}

func splitYAMLDocuments(data []byte) [][]byte {
	lines := bytes.Split(data, []byte("\n"))
	var chunks [][]byte
	var current [][]byte
	flush := func() {
		if len(current) > 0 {
			chunks = append(chunks, bytes.Join(current, []byte("\n")))
			current = nil
		}
	}
	for _, line := range lines {
		if bytes.Equal(bytes.TrimSpace(line), []byte("---")) {
			flush()
			continue
		}
		current = append(current, line)
	}
	flush()
	return chunks
}

// targetRef identifies the object a policy or route attaches to.
type targetRef struct {
	kind      string
	namespace string
	name      string
}

// Check inspects a decoded manifest set and returns one Violation per
// HTTPRoute that carries an InferencePool backendRef (i.e. is on the
// inference path) and is not covered by an AuthPolicy -- attached either to
// the route itself or to its parent Gateway -- that overwrites
// ObjectiveHeaderKey in spec.rules.response.success.headers.
func Check(docs []object) ([]Violation, error) {
	covered := map[targetRef]bool{}
	for _, doc := range docs {
		if !isKind(doc, "AuthPolicy") {
			continue
		}
		ref, ok := authPolicyTarget(doc)
		if !ok {
			continue
		}
		if authPolicyStripsObjective(doc) {
			covered[ref] = true
		}
	}

	var violations []Violation
	for _, doc := range docs {
		if !isKind(doc, "HTTPRoute") {
			continue
		}
		if !isInferenceRoute(doc) {
			continue
		}
		ns, name := metaNamespaceName(doc)
		if ns == "" || name == "" {
			return nil, fmt.Errorf("HTTPRoute missing metadata.namespace/name")
		}

		routeRef := targetRef{kind: "HTTPRoute", namespace: ns, name: name}
		if covered[routeRef] {
			continue
		}

		gatewayCovered := false
		for _, gwRef := range parentGateways(doc, ns) {
			if covered[gwRef] {
				gatewayCovered = true
				break
			}
		}
		if gatewayCovered {
			continue
		}

		violations = append(violations, Violation{
			Namespace: ns,
			Name:      name,
			Reason: fmt.Sprintf(
				"routes to an InferencePool but no AuthPolicy on this route or its parent Gateway overwrites %s",
				ObjectiveHeaderKey,
			),
		})
	}

	sort.Slice(violations, func(i, j int) bool {
		if violations[i].Namespace != violations[j].Namespace {
			return violations[i].Namespace < violations[j].Namespace
		}
		return violations[i].Name < violations[j].Name
	})
	return violations, nil
}

func isKind(doc object, kind string) bool {
	k, _ := doc["kind"].(string)
	return k == kind
}

func metaNamespaceName(doc object) (namespace, name string) {
	meta, _ := doc["metadata"].(map[string]any)
	if meta == nil {
		return "", ""
	}
	ns, _ := meta["namespace"].(string)
	n, _ := meta["name"].(string)
	return ns, n
}

// isInferenceRoute reports whether any rule in the HTTPRoute backs onto an
// InferencePool, under either the x-k8s.io (alpha) or k8s.io (stable) API
// group -- this cluster's gateway controller and the EPP disagree on which
// one they accept, so deploy/poc/02-epp.yaml declares both. A route that only
// ever reaches a plain Service never passes through the EPP's ext_proc filter
// and is out of scope for this check.
func isInferenceRoute(doc object) bool {
	spec, _ := doc["spec"].(map[string]any)
	rules, _ := spec["rules"].([]any)
	for _, r := range rules {
		rule, _ := r.(map[string]any)
		backendRefs, _ := rule["backendRefs"].([]any)
		for _, b := range backendRefs {
			ref, _ := b.(map[string]any)
			kind, _ := ref["kind"].(string)
			group, _ := ref["group"].(string)
			if kind == "InferencePool" &&
				(group == "inference.networking.x-k8s.io" || group == "inference.networking.k8s.io") {
				return true
			}
		}
	}
	return false
}

// parentGateways returns the (possibly cross-namespace) Gateways an
// HTTPRoute attaches to, defaulting an unset parentRef namespace to the
// route's own namespace per the Gateway API spec.
func parentGateways(doc object, routeNamespace string) []targetRef {
	spec, _ := doc["spec"].(map[string]any)
	parentRefs, _ := spec["parentRefs"].([]any)
	var refs []targetRef
	for _, p := range parentRefs {
		pr, _ := p.(map[string]any)
		kind, _ := pr["kind"].(string)
		if kind != "" && kind != "Gateway" {
			continue
		}
		name, _ := pr["name"].(string)
		if name == "" {
			continue
		}
		ns, _ := pr["namespace"].(string)
		if ns == "" {
			ns = routeNamespace
		}
		refs = append(refs, targetRef{kind: "Gateway", namespace: ns, name: name})
	}
	return refs
}

// authPolicyTarget reads spec.targetRef off an AuthPolicy. A policy without
// one (for example a JSON-merge-patch fragment meant to be applied with
// `oc patch` against an existing, controller-managed AuthPolicy -- see
// docs/gateway-header-stripping.md) is skipped here and must be matched by a
// live snapshot showing the real, merged object instead.
func authPolicyTarget(doc object) (targetRef, bool) {
	spec, _ := doc["spec"].(map[string]any)
	tr, _ := spec["targetRef"].(map[string]any)
	if tr == nil {
		return targetRef{}, false
	}
	kind, _ := tr["kind"].(string)
	name, _ := tr["name"].(string)
	if kind == "" || name == "" {
		return targetRef{}, false
	}
	ns, _ := tr["namespace"].(string)
	if ns == "" {
		ns, _ = metaNamespaceName(doc)
	}
	return targetRef{kind: kind, namespace: ns, name: name}, true
}

// authPolicyStripsObjective reports whether the AuthPolicy sets
// ObjectiveHeaderKey as a response.success header with a non-empty value
// source. Kuadrant's AuthPolicy sends these to Authorino, which returns them
// to Envoy's ext_authz filter as OkHttpResponse headers with append_action
// left at its (override) default -- see docs/gateway-header-stripping.md for
// the citation -- so a header present here replaces a client-forged value of
// the same name before the EPP's ext_proc filter ever sees it.
func authPolicyStripsObjective(doc object) bool {
	spec, _ := doc["spec"].(map[string]any)
	rules, _ := spec["rules"].(map[string]any)
	response, _ := rules["response"].(map[string]any)
	success, _ := response["success"].(map[string]any)
	headers, _ := success["headers"].(map[string]any)
	for key, v := range headers {
		if !strings.EqualFold(key, ObjectiveHeaderKey) {
			continue
		}
		entry, _ := v.(map[string]any)
		if hasNonEmptyValueSource(entry) {
			return true
		}
	}
	return false
}

// hasNonEmptyValueSource reports whether an Authorino ValueOrSelector-shaped
// map (plain.expression, plain.value, value, selector, ...) actually carries
// something, rather than being present but empty.
func hasNonEmptyValueSource(entry map[string]any) bool {
	if entry == nil {
		return false
	}
	if s, ok := entry["value"].(string); ok && s != "" {
		return true
	}
	if _, ok := entry["value"]; ok {
		if _, isString := entry["value"].(string); !isString {
			return true // non-string static value, e.g. a number or bool
		}
	}
	if plain, ok := entry["plain"].(map[string]any); ok {
		if expr, ok := plain["expression"].(string); ok && expr != "" {
			return true
		}
		if sel, ok := plain["selector"].(string); ok && sel != "" {
			return true
		}
	}
	if expr, ok := entry["expression"].(string); ok && expr != "" {
		return true
	}
	if sel, ok := entry["selector"].(string); ok && sel != "" {
		return true
	}
	return false
}
