#!/usr/bin/env python3
"""Render an N-group variant of deploy/poc/00-config.yaml (UNI-187).

00-config.yaml's 3-group table (app1/app2/end-users) is the committed default
every edge case restores to (rule 3), so it is NOT edited here. This script
prints a copy of it with ONLY the `groups:` list swapped for one of the tables
below; every other line -- enforce, halfLife, flowControl, the comments -- is
byte-identical to whatever 00-config.yaml says at the time you run it, so the
variant cannot drift from the default.

    render.py <table> [--weights SET] [--name CM-NAME] [--src PATH]
    render.py --verify          # committed renders == fresh renders

Tables:
    6      app1..app6           UNI-165
    20     app1..app20          UNI-167
    smoke  app3..app8           20-n-group-smoke.sh: six NEW identities, all
                                of which also reference maas-vllm-cpu (the
                                pre-UNI-187 app1-production/app2-batch do not)

Weight sets (--weights, default equal):
    equal     every group the same
    graded    40/20/15/10/10/5   (6-group tables only)
    dominant  90/2/2/2/2/2       (6-group tables only)
    pow2      32/16/8/4/2/1      (6-group tables only)

Weights are relative, as in 00-config.yaml. defaultGroup (unclassified,
weight 5) is left as-is: no case sends unclassified traffic, and if one ever
lands there that is the bug to see, not a share to hide.

Applying the output to `maas-epp-config` RECREATES BOTH EPPs (the CPU and GPU
LLMISVCs read the same ConfigMap) and zeroes their per-group counters. Do it
before a run, never during one, and only from the case that owns the GPU
queue. Restore with `oc apply -f deploy/poc/00-config.yaml`. Once a table is
live, a single weight can be moved between runs with the benchmark's
`epp-weight:<group>` LIVE_SET_TARGET (UNI-180).
"""
import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_SRC = os.path.join(HERE, "..", "00-config.yaml")

# group name -> exact-match MaaSSubscription name. app1/app2 keep their
# historical subscription names; app3+ use the bare group name for all four
# of subscription / key file / match value / loadgen group (08-tenants.yaml).
def subscription(group):
    return {"app1": "app1-production", "app2": "app2-batch"}.get(group, group)

TABLES = {
    "6": [f"app{n}" for n in range(1, 7)],
    "20": [f"app{n}" for n in range(1, 21)],
    "smoke": [f"app{n}" for n in range(3, 9)],
}

SIX = {
    "graded": [40, 20, 15, 10, 10, 5],
    "dominant": [90, 2, 2, 2, 2, 2],
    "pow2": [32, 16, 8, 4, 2, 1],
}

# Committed renders, checked by --verify: (table, weights, configmap name).
COMMITTED = {
    "6-group-equal.yaml": ("6", "equal", "maas-epp-config"),
    "20-group-equal.yaml": ("20", "equal", "maas-epp-config"),
    "smoke-6-group.yaml": ("smoke", "equal", "maas-epp-config-smoke"),
}


def weights_for(table, weight_set):
    groups = TABLES[table]
    if weight_set == "equal":
        w = round(100 / len(groups), 1)
        return [w] * len(groups)
    if len(groups) != 6:
        sys.exit(f"--weights {weight_set} is defined for 6-group tables only")
    return SIX[weight_set]


def fmt_weight(w):
    return str(int(w)) if float(w).is_integer() else str(w)


def render(src_text, table, weight_set, cm_name):
    groups = TABLES[table]
    weights = weights_for(table, weight_set)

    m = re.search(r"^([ \t]*)groups:[ \t]*\n((?:\1[ \t]+- \{.*\}[ \t]*\n)+)",
                  src_text, re.MULTILINE)
    if not m:
        sys.exit("render: no `groups:` list of `- { ... }` lines found in the source")
    item_indent = re.match(r"[ \t]*", m.group(2)).group(0)
    width = max(len(g) for g in groups) + 1
    lines = [f"{item_indent}# UNI-187 variant: table={table} weights={weight_set}. "
             "Generated by deploy/poc/epp-groups/render.py -- do not hand-edit.\n"]
    for g, w in zip(groups, weights):
        lines.append(f"{item_indent}- {{ name: {(g + ',').ljust(width)} "
                     f"weight: {fmt_weight(w)}, match: {{ exact: [{subscription(g)}] }} }}\n")
    out = src_text[:m.start(2)] + "".join(lines) + src_text[m.end(2):]

    out, n = re.subn(r"^(metadata:\n  name: )maas-epp-config$", r"\g<1>" + cm_name,
                     out, count=1, flags=re.MULTILINE)
    if n != 1:
        sys.exit("render: could not find `metadata.name: maas-epp-config` in the source")
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("table", nargs="?", choices=sorted(TABLES))
    ap.add_argument("--weights", default="equal", choices=["equal"] + sorted(SIX))
    ap.add_argument("--name", default="maas-epp-config")
    ap.add_argument("--src", default=DEFAULT_SRC)
    ap.add_argument("--verify", action="store_true")
    a = ap.parse_args()
    src_text = open(a.src).read()

    if a.verify:
        bad = 0
        for fname, (table, ws, name) in COMMITTED.items():
            path = os.path.join(HERE, fname)
            fresh = render(src_text, table, ws, name)
            if not os.path.exists(path) or open(path).read() != fresh:
                print(f"STALE {fname}: re-run `render.py {table} --weights {ws} --name {name} > {fname}`")
                bad = 1
            else:
                print(f"ok    {fname}")
        sys.exit(bad)

    if not a.table:
        ap.error("a table is required unless --verify")
    sys.stdout.write(render(src_text, a.table, a.weights, a.name))


if __name__ == "__main__":
    main()
